// The API contract for clients other than the web pages (the native iOS app). `npm run api:catalog`
// writes these to docs/api/, and a test fails when they are stale, so any change to commands,
// shared wording, or routes shows up as a diff the iOS side must react to.
import { z } from 'zod'
import { commands } from './commands/registry'
import { APP_ROUTES, WEB_ONLY_PAGES } from '@/lib/app-routes'
import {
  BOOKING_STATUS_LABELS, KIND_LABELS, PAYMENT_PURPOSE_LABELS, PAYMENT_RULE_LABELS, ROSTER_PAYMENT_LABELS, ROSTER_STATUS_LABELS, WEEKDAY_LABELS,
  formatMoney, levelLabel, policyLabel, priceLabel, seatsLabel, type LevelSystem, type PaymentRule,
} from '@/lib/format'
import { US_TIME_ZONES, formatDateTime, formatDayHeading, formatSessionRange, formatTime } from '@/lib/time'

const API_DOCS_DIR = 'docs/api'

/** docs/api/commands.json: every command with its access rule and input JSON Schema. */
export function commandCatalog() {
  return {
    note: 'Generated by `npm run api:catalog` from src/server/commands/registry.ts. Do not edit. POST /api/commands/<name> with the input as JSON; responses are { data } or { error: { code, message, details } }.',
    commands: Object.entries(commands)
      .sort(([a], [b]) => a.localeCompare(b))
      .map(([name, c]) => ({
        name,
        access: c.access,
        mutates: c.mutates,
        summary: c.summary,
        input: z.toJSONSchema(c.input, { io: 'input', unrepresentable: 'any' }),
      })),
  }
}

// Vectors are produced by Node's ICU, so the drift test also catches an ICU change (e.g. a Node upgrade).
type Vector = { args: unknown[]; out: unknown }
const vectors = <A extends unknown[]>(fn: (...args: A) => unknown, cases: A[]): Vector[] => cases.map((args) => ({ args, out: fn(...args) }))

// Instants chosen to cover morning/evening, minutes, midnight, a session that crosses midnight,
// and both sides of the 2026 US daylight-saving changes (Mar 8, Nov 1).
const INSTANTS: [string, string][] = [
  ['2026-12-02T02:00:00.000Z', '2026-12-02T03:30:00.000Z'],
  ['2026-07-01T16:05:00.000Z', '2026-07-01T17:00:00.000Z'],
  ['2026-03-08T09:30:00.000Z', '2026-03-08T11:00:00.000Z'],
  ['2026-11-01T08:30:00.000Z', '2026-11-01T10:00:00.000Z'],
  ['2026-01-15T07:45:00.000Z', '2026-01-15T08:15:00.000Z'],
]
const ZONES = US_TIME_ZONES.map((z) => z.value).concat('UTC')

/**
 * docs/api/strings.json: wording the web computes on the client, as data. Label maps are used as
 * they are; formatter vectors are outputs of the real TS functions that Swift must reproduce
 * character for character. They come from Node's ICU (Node 22 locally and in CI).
 */
export function sharedStrings() {
  const rules: PaymentRule[] = ['free', 'pay_now', 'pay_after', 'external']
  const systems: (LevelSystem | null)[] = ['utr', 'ntrp', 'wtn', null]
  const instants = INSTANTS.flatMap(([start, end]) => ZONES.map((zone) => [start, end, zone] as const))
  return {
    note: 'Generated by `npm run api:catalog` from src/lib/format.ts and src/lib/time.ts. Do not edit.',
    labels: {
      offeringKind: KIND_LABELS,
      paymentRule: PAYMENT_RULE_LABELS,
      paymentPurpose: PAYMENT_PURPOSE_LABELS,
      weekday: WEEKDAY_LABELS,
      bookingStatus: BOOKING_STATUS_LABELS,
      rosterStatus: ROSTER_STATUS_LABELS,
      rosterPayment: ROSTER_PAYMENT_LABELS,
      timeZones: US_TIME_ZONES,
    },
    vectors: {
      formatMoney: vectors(formatMoney, [[0], [5], [99], [100], [6000], [6050], [123456], [100000000], [-2500]]),
      priceLabel: vectors(priceLabel, rules.flatMap((r) => [[0, r], [6000, r], [4550, r]] as [number, PaymentRule][])),
      levelLabel: vectors(levelLabel, systems.flatMap((s) => [[s, 4, 7], [s, 3.5, null], [s, null, 9.5], [s, null, null]] as [LevelSystem | null, number | null, number | null][])),
      seatsLabel: vectors(seatsLabel, [[0, 1, 0], [1, 1, 0], [0, 8, 0], [3, 8, 0], [8, 8, 0], [8, 8, 2], [9, 8, 0], [2, 2, 1]]),
      policyLabel: vectors(policyLabel, [[24, 50, 100], [0, 0, 0], [48, 0, 100], [12, 25, 0], [1, 100, 100]]),
      formatDateTime: vectors((instant: string, zone: string) => formatDateTime(instant, zone), instants.map(([s, , z]) => [s, z])),
      formatDate: {
        note: 'formatDateTime(instant, zone, { hour: undefined, minute: undefined })',
        cases: vectors((instant: string, zone: string) => formatDateTime(instant, zone, { hour: undefined, minute: undefined }), instants.map(([s, , z]) => [s, z])),
      },
      formatTime: vectors(formatTime, instants.map(([s, , z]) => [s, z])),
      formatDayHeading: vectors(formatDayHeading, instants.map(([s, , z]) => [s, z])),
      formatSessionRange: vectors(formatSessionRange, instants.map(([s, e, z]) => [s, e, z])),
    },
  }
}

/** docs/api/routes.json: the native Router's table (see src/lib/app-routes.ts). */
function routeTable() {
  return {
    note: 'Generated by `npm run api:catalog` from src/lib/app-routes.ts. Do not edit. First match wins; unknown paths open in Safari.',
    routes: APP_ROUTES,
    webOnly: WEB_ONLY_PAGES,
  }
}

/** VamoKit bundles its own copies (SwiftPM resources must live inside the package). */
const VAMOKIT_RESOURCES = 'ios-native/VamoKit/Sources/VamoKit/Resources'

/** Repo-relative path → contents, for everything `npm run api:catalog` writes. */
export function apiDocs(): Record<string, string> {
  const json = (value: unknown) => `${JSON.stringify(value, null, 2)}\n`
  const strings = json(sharedStrings())
  const routes = json(routeTable())
  return {
    [`${API_DOCS_DIR}/commands.json`]: json(commandCatalog()),
    [`${API_DOCS_DIR}/strings.json`]: strings,
    [`${API_DOCS_DIR}/routes.json`]: routes,
    [`${VAMOKIT_RESOURCES}/strings.json`]: strings,
    [`${VAMOKIT_RESOURCES}/routes.json`]: routes,
  }
}
